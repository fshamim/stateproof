package generated.stateproof

import io.stateproof.sample.AppEvent
import io.stateproof.sample.AppState
import io.stateproof.sample.TaskItem
import io.stateproof.sample.TaskProofRuntime
import io.stateproof.sample.defaultSeedTasks
import kotlin.test.assertEquals

fun eventForTransition(
    currentState: AppState,
    transition: String,
    runtime: TaskProofRuntime,
): AppEvent {
    val parts = transition.split("_")
    require(parts.size == 3) {
        "Expected transition format Source_Event_Target but got '$transition'"
    }

    val eventName = parts[1]
    val targetState = parts[2]
    val tasks = runtime.stateData._tasks.value
    val firstExistingId = tasks.firstOrNull()?.id ?: defaultSeedTasks().first().id
    val selectedId = runtime.stateData._selectedTaskId.value
    val existingId = selectedId?.takeIf { id -> tasks.any { it.id == id } } ?: firstExistingId

    return when (eventName) {
        "OnAppStart" -> AppEvent.OnAppStart
        "OnBack" -> AppEvent.OnBack
        "OnCreateTaskTap" -> AppEvent.OnCreateTaskTap
        "OnSettingsTap" -> AppEvent.OnSettingsTap
        "OnLogout" -> AppEvent.OnLogout
        "OnRetry" -> AppEvent.OnRetry

        "OnLoginSubmit" -> {
            if (targetState == "Authenticating") {
                AppEvent.OnLoginSubmit(username = "demo", password = "demo")
            } else {
                AppEvent.OnLoginSubmit(username = "", password = "")
            }
        }

        "OnAuthSuccess" -> {
            val token = runtime.stateData._authToken.value.ifBlank { "taskproof-token" }
            AppEvent.OnAuthSuccess(token = token)
        }

        "OnAuthFailed" -> {
            val reason = runtime.stateData._authErrorReason.value ?: "Invalid username or password"
            AppEvent.OnAuthFailed(reason = reason)
        }

        "OnTasksLoaded" -> {
            val loaded = tasks.ifEmpty { defaultSeedTasks() }
            AppEvent.OnTasksLoaded(tasks = loaded)
        }

        "OnTasksLoadFailed" -> {
            val reason = runtime.stateData._authErrorReason.value ?: "Task load failed"
            AppEvent.OnTasksLoadFailed(reason = reason)
        }

        "OnSelectTask" -> {
            if (targetState == "TaskDetail") {
                AppEvent.OnSelectTask(id = existingId)
            } else {
                AppEvent.OnSelectTask(id = "__missing_task__")
            }
        }

        "OnSaveTask" -> {
            if (targetState == "SavingTask") {
                AppEvent.OnSaveTask(
                    title = "Generated task",
                    description = "Generated by StateProof desktop tests",
                )
            } else {
                AppEvent.OnSaveTask(title = "", description = "invalid")
            }
        }

        "OnToggleTask" -> AppEvent.OnToggleTask(id = existingId)
        "OnDeleteTask" -> AppEvent.OnDeleteTask(id = existingId)
        "OnTaskDeleted" -> AppEvent.OnTaskDeleted(id = existingId)

        "OnTaskToggled" -> {
            val currentCompleted = tasks.firstOrNull { it.id == existingId }?.completed ?: false
            AppEvent.OnTaskToggled(id = existingId, completed = !currentCompleted)
        }

        "OnTaskSaved" -> {
            val nextIndex = tasks.size + 1
            AppEvent.OnTaskSaved(
                task = TaskItem(
                    id = "task-generated-$nextIndex",
                    title = "Generated task $nextIndex",
                    description = "Generated by StateProof path test",
                    completed = false,
                ),
            )
        }

        "OnTaskSaveFailed" -> {
            val reason = runtime.stateData._authErrorReason.value ?: "Task operation failed"
            AppEvent.OnTaskSaveFailed(reason = reason)
        }

        else -> error(
            "No event mapping for transition '$transition' from state '${currentState::class.simpleName}'",
        )
    }
}

fun assertGeneratedTransitions(expectedTransitions: List<String>, actualTransitions: List<String>) {
    assertEquals(
        expectedTransitions,
        actualTransitions,
        "Transition log mismatch.\nExpected: $expectedTransitions\nActual:   $actualTransitions",
    )
}
